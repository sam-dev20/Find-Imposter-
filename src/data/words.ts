export function getRandomWord(): WordItem {
  const randomIndex = Math.floor(Math.random() * WORD_DATABASE.length);
  return WORD_DATABASE[randomIndex];
}

export function getDistinctHintsForWord(
  wordItem: WordItem,
  count: number
): Array<{ en: string; bn: string }> {
  const enList = wordItem.hints && wordItem.hints.length > 0 ? wordItem.hints : [wordItem.hint];
  const bnList = wordItem.hintsBn && wordItem.hintsBn.length > 0 ? wordItem.hintsBn : [wordItem.hintBn];

  const pairs: Array<{ en: string; bn: string }> = enList.map((en, idx) => ({
    en,
    bn: bnList[idx] || bnList[0] || en,
  }));

  const shuffled = [...pairs].sort(() => Math.random() - 0.5);

  const result: Array<{ en: string; bn: string }> = [];
  for (let i = 0; i < count; i++) {
    result.push(shuffled[i % shuffled.length]);
  }
  return result;
}
