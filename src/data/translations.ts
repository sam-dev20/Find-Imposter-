export function getTranslation(lang: Language) {
  return TRANSLATIONS[lang] || TRANSLATIONS.en;
}

export function toBanglaNumber(num: number | string): string {
  const banglaDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (digit) => banglaDigits[parseInt(digit, 10)]);
}

export function formatPlayerNumber(num: number | string, lang: Language): string {
  return lang === 'bn' ? toBanglaNumber(num) : String(num);
}

export function getDefaultPlayerName(index: number, lang: Language): string {
  if (lang === 'bn') {
    return `খেলোয়াড় ${toBanglaNumber(index)}`;
  }
  return `Player ${index}`;
}

